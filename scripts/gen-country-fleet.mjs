#!/usr/bin/env node
// Derive the compiled country-fleet table from scripts/country-fleet.json.
//
// Purely mechanical — every number and citation lives in the JSON (single
// reviewable source, /gg consensus); this script only applies the documented
// derivation and emits pipeline/lib/country-fleet.generated.ts. Phase 1.5
// will add a second emitter for engine/noise-compute (Rust) from the same
// JSON once the engine fallback-mix policy is decided.
//
// Derivation (ownership → traffic):
//   moto_traffic_share = override                                 when calibrated
//                      | clamp(factor(continent) × ownership,     when WHO fleet known
//                              0.01, 0.45)                        and factor defined
//                      | continent band | WORLD
//
// The ownership→traffic factor is CONTINENT-specific because usage intensity
// differs structurally — calibrated on countries where both sides are known:
//   Asia 0.40           TH ownership 0.517 → enricher traffic 0.20 (0.39);
//                       daily-transport motos.
//   Europe 0.15         CZ ownership 0.20 → RSD-measured traffic ~0.03 (0.15);
//                       PL 0.093 → GPR ~0.02 (0.21); recreational fleets.
//   North America 0.15  US 0.030 → HPMS-fallback 0.01 (weekend fleets).
//   South America 0.20  BR ownership 0.271 → DNIT enricher split 0.05 (0.18).
//   Oceania 0.15        same recreational pattern as EU/NA.
//   Africa — NO derivation: registration is blind to the informal boda-boda/
//   okada fleets (KE registered ownership 7 % vs calibrated traffic 20 %+),
//   so only the continent band or a calibrated override applies.
//
// Usage: node scripts/gen-country-fleet.mjs   (then commit JSON + generated TS)

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const FLEET_JSON = resolve(__dirname, 'country-fleet.json')
const OUT_TS = resolve(__dirname, '..', 'pipeline', 'lib', 'country-fleet.generated.ts')

const OWNERSHIP_TO_TRAFFIC_BY_CONTINENT = {
  Asia: 0.4,
  Europe: 0.15,
  'North America': 0.15,
  'South America': 0.2,
  Oceania: 0.15,
  // Africa intentionally absent — see header.
}
const TRAFFIC_SHARE_CLAMP = [0.01, 0.45]
const TPD_CLAMP = [0.8, 6.0]
// Curated/continent trips-per-dwelling rows are entered in their surveys'
// native unit (per OCCUPIED household); the trip model multiplies by
// GFA-estimated STOCK dwellings, so the generator folds the ~8 % vacancy in
// here (OECD HM1-1) — mixing the two denominators overstated every curated
// country by ~8 % (/gg diff review). WORLD 3.68 already contains the factor
// (4.0 × 0.92) and is exempt.
const OCCUPANCY = 0.92

const clamp = (v, [lo, hi]) => Math.min(Math.max(v, lo), hi)
const round = (v, places) => Number(v.toFixed(places))

const data = JSON.parse(readFileSync(FLEET_JSON, 'utf8'))
const { world, continents, countries } = data

const rows = []
for (const [iso2, row] of Object.entries(countries).sort()) {
  const continent = continents[row.continent] ?? null

  const ownershipFactor = OWNERSHIP_TO_TRAFFIC_BY_CONTINENT[row.continent]
  let moto
  let motoSrc
  if (row.moto_traffic_share_override !== undefined) {
    moto = row.moto_traffic_share_override
    motoSrc = 'calibrated override'
  } else if (row.fleet?.moto_fleet_share !== undefined && ownershipFactor !== undefined) {
    moto = clamp(ownershipFactor * row.fleet.moto_fleet_share, TRAFFIC_SHARE_CLAMP)
    motoSrc = `${ownershipFactor} x ownership ${row.fleet.moto_fleet_share} (WHO ${row.fleet.year})`
  } else if (continent) {
    moto = continent.moto_traffic_share
    motoSrc = `${row.continent} band`
  } else {
    moto = world.moto_traffic_share
    motoSrc = 'WORLD'
  }

  let tpd
  let tpdSrc
  if (row.vehicle_trips_per_occupied_dwelling !== undefined) {
    tpd = row.vehicle_trips_per_occupied_dwelling * OCCUPANCY
    tpdSrc = 'curated ×0.92 occ'
  } else if (continent) {
    tpd = continent.vehicle_trips_per_occupied_dwelling * OCCUPANCY
    tpdSrc = `${row.continent} band ×0.92 occ`
  } else {
    tpd = world.vehicle_trips_per_occupied_dwelling // already stock-denominated
    tpdSrc = 'WORLD'
  }

  rows.push({
    iso2,
    moto: round(clamp(moto, TRAFFIC_SHARE_CLAMP), 3),
    tpd: round(clamp(tpd, TPD_CLAMP), 2),
    comment: `${motoSrc}; tpd ${tpdSrc}`,
  })
}

const body = rows
  .map((r) => `  ${r.iso2}: { motoTrafficShare: ${r.moto}, tripsPerDwelling: ${r.tpd} }, // ${r.comment}`)
  .join('\n')

const ts = `/**
 * GENERATED by scripts/gen-country-fleet.mjs from scripts/country-fleet.json —
 * DO NOT EDIT. Quantity definitions, per-row citations, and the
 * ownership→traffic derivation are documented in the JSON.
 *
 * Fallback local-road vehicle mix + residential trip generation for the
 * service-tree heuristic. This is NOT a global split SSOT: national censuses
 * (measured, provenance rank ≥ 6) keep their own source-specific splits.
 */

export interface CountryFleet {
  /** Share of powered 2-/3-wheelers in daily local-road vehicle flow. */
  motoTrafficShare: number
  /** Motor-vehicle trips per STOCK dwelling per day, both directions —
   *  survey per-household values are ×0.92 occupancy-folded at generation,
   *  matching the GFA-estimated stock dwellings the trip model multiplies. */
  tripsPerDwelling: number
}

/** Terminal of the cascade — the pre-2026-07 service-tree constants. Medium/
 *  heavy local-road shares stay world-constant (no per-country signal):
 *  medium 0.01, heavy 0.02 (see splitAADT). */
export const WORLD_FLEET: CountryFleet = {
  motoTrafficShare: ${world.moto_traffic_share},
  tripsPerDwelling: ${world.vehicle_trips_per_occupied_dwelling},
}

const COUNTRY_FLEET: Record<string, CountryFleet> = {
${body}
}

/** Country → fleet row; unknown/missing ISO falls to WORLD_FLEET (continent
 *  bands are resolved into the per-country rows at generation time). */
export function fleetForIso(iso2: string | undefined): CountryFleet {
  return (iso2 !== undefined && COUNTRY_FLEET[iso2]) || WORLD_FLEET
}
`

writeFileSync(OUT_TS, ts)
console.log(`country-fleet.generated.ts: ${rows.length} country rows written`)
